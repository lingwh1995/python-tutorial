"""python 中元组的定义

1. 元组概述
   元组是不可变的有序序列，与列表类似，但创建后不能修改，适合存放不应被改变的一组数据。

2. 元组特点
   - 有序：支持下标索引和切片
   - 不可变：不支持增、删、改元素
   - 可存储任意类型元素，元素允许重复
   - 支持遍历、统计、成员判断等只读操作

3. 语法定义
   - 使用小括号 () 定义，元素之间用逗号分隔
     t1 = (值1, 值2, 值3 ...)
   - 小括号可以省略，直接写 1, 2, 3 也是元组
     t1 = 值1, 值2, 值3 ...
   - 只有一个元素时必须带尾逗号，(1,) 才是元组，(1) 只是数字
     t2 = (值1,)
   - 空元组用 () 或 tuple() 表示
     t3 = tuple()
     t4 = ()

4. 注意事项
   - 不可变指的是元组中的引用不可变，若元素是列表，列表内部仍可修改
   - tuple() 只能接收一个可迭代对象参数
   - 元组不可变，修改元组的操作都会抛出 TypeError

@author lingwh
@date 2026/10/20 17:13
"""

# 定义多个数据元组
t1 = (10, 20, 30)
# 定义单个数据元组
t2 = (10,)
t3 = ('Smith', 23, '95.2', True)

# 下面定义的不是元组
i = (10)
s = ('hello')

print(type(t1))
print(type(t2))
print(type(t3))
print(type(i))
print(type(s))